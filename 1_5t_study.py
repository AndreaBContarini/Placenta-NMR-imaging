"""# **Parte 2**: **FIT**

Akaike information criterion (AIC) is defined as:

$ AIC = N_b \cdot log(MSE) \cdot \dfrac{ 2k (k +1)}{N_b - k - 1} $

where $N_b$ is the number of $b$-values, $MSE$ is the mean squared error, and $k$ is the number of the model’s parameters.

$k=4$ per 2-perf; $k=4$ per IVIM; $k=2$ per mononexponential
"""

# Function to calculate: Akaike Information Criterion (AIC)
def calculate_AIC(MSE, k, N_b):
    return N_b * np.log(MSE) + 2 * k * (k + 1) / (N_b - k - 1)

# Function to calculate: mean and standard deviation within ROI (regions of interes)
def calculate_mean_and_std(param_map, mask_data):
    # Calculate mean within ROI
    mean_roi = np.mean(param_map[mask_data != 0])

    # Calculate standard deviation corrected for the number of voxels
    std_roi = np.std(param_map[mask_data != 0], ddof=1) / np.sqrt(np.count_nonzero(mask_data))
    return mean_roi, std_roi

