class IVIM():
  def __init__(self, D:float): #parametro D fissato
    self.D = D

  def uncertainty(self, b, pcov):
        return np.sqrt(np.diag(pcov))

  def function(self,b,f,D_star,S0):
    return S0* (f * np.exp(-b*D_star) + (1-f)*np.exp(-b*self.D))

  def function_alpha(self,b,f,D_star,S0,alpha):
    return S0* (f * np.exp(-b*D_star) + alpha * (1-f)*np.exp(-b*self.D))

class Perfusion():
    def __init__(self, D:float, f:float): #parametri D ed f fissati
        self.D = D
        self.f = f

    def function2(self, b, D1_star, D2_star, f1, S0):
      return S0 * (f1 * np.exp(-(D1_star + D2_star + self.D) * b) +
                  (self.f - f1) * np.exp(-(D2_star + self.D) * b) +
                   (1 - self.f) * np.exp(-self.D * b))

    def function2_alpha(self, b, D1_star, D2_star, f1, S0):
      return S0 * (f1 * np.exp(-(D1_star + D2_star + self.D) * b) +
                  (self.f - f1) * np.exp(-(D2_star + self.D) * b) +
                  self.alpha * (1 - self.f) * np.exp(-self.D * b))

    def uncertainty(self, b, pcov):
        return np.sqrt(np.diag(pcov))

