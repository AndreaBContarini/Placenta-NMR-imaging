"""#Test Kolmogorov-Smirnov

Il p-value indica la probabilità che le differenze osservate tra le distribuzioni siano dovute al caso. Un p-value alto (tipicamente maggiore di 0.05) suggerisce che non ci sono prove sufficienti per rifiutare l'ipotesi nulla, ossia che i dati osservati provengano dalla stessa distribuzione dei dati previsti dal modello.

##**Fetal**
"""

from scipy.stats import kstest

signal_fetal_mean = fetal_mean
signal_fetal_std = fetal_error
# popt_mean_fetal_2perf: parametri del modello Two-Perfusion
# popt_ivim_mean_fetal: parametri del modello IVIM
# popt_mono_mean_fetal: parametri del modello Monoexponential

#  valori previsti dai modelli per ogni punto dati
predicted_two_perfusion = perfusion_model_fetal.function2(b_values, *popt_mean_fetal_2perf)
predicted_ivim = ivim_model_fetal.function(b_values, *popt_ivim_mean_fetal)
predicted_mono = monoexponential_model(b_values, *popt_mono_mean_fetal)

# Funzione per il test di Kolmogorov-Smirnov
def perform_ks_test(observed, predicted):
    # Esegui il test di KS confrontando i dati osservati con quelli previsti
    ks_statistic, p_value = kstest(observed, 'norm', args=(np.mean(predicted), np.std(predicted)))
    return ks_statistic, p_value

# test di Kolmogorov-Smirnov per ogni modello
